#!/usr/bin/env python3
"""Generate configs/ijcs_ext/*.yaml: lambda base configs with batch / queue / backbone overrides."""

from __future__ import annotations

import copy
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "configs" / "ijcs_ext"

SEMEVAL_BASE = {
    "002": "configs/semeval2018_l002.yaml",
    "005": "configs/semeval2018_l005.yaml",
    "010": "configs/semeval2018.yaml",
    "020": "configs/semeval2018_l020.yaml",
    "050": "configs/semeval2018_l050.yaml",
}
GOEMO_BASE = {
    "002": "configs/tune/clfer_lt_l002.yaml",
    "005": "configs/tune/clfer_lt_l005.yaml",
    "010": "configs/tune/clfer_lt_l010.yaml",
    "020": "configs/tune/clfer_lt_l020.yaml",
    "050": "configs/default.yaml",
}

# (dataset, lambda tag, variant tag, overrides)
VARIANTS: list[tuple[str, str, str, dict]] = []
for tag in SEMEVAL_BASE:
    VARIANTS.append(("semeval", tag, "b8", {"training.batch_size": 8}))
for tag in ("002", "010", "050"):
    VARIANTS.append(("semeval", tag, "b16", {"training.batch_size": 16}))
for tag in ("010", "050"):
    VARIANTS.append(("goemo", tag, "b128", {"training.batch_size": 128}))
VARIANTS.append(("goemo", "050", "b64", {"training.batch_size": 64}))
VARIANTS.append(("goemo", "050", "q1024", {"model.queue_size": 1024}))
VARIANTS.append(("goemo", "050", "q16384", {"model.queue_size": 16384}))
VARIANTS.append(("semeval", "050", "q512", {"model.queue_size": 512}))
VARIANTS.append(("semeval", "050", "q8192", {"model.queue_size": 8192}))
for ds in ("goemo", "semeval"):
    for tag in ("002", "005", "010", "020", "050"):
        VARIANTS.append((ds, tag, "bert", {"model.backbone": "bert-base-uncased"}))


def config_path(ds: str, tag: str, variant: str) -> str:
    return f"configs/ijcs_ext/{ds}_l{tag}_{variant}.yaml"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for ds, tag, variant, overrides in VARIANTS:
        base = SEMEVAL_BASE[tag] if ds == "semeval" else GOEMO_BASE[tag]
        cfg = copy.deepcopy(yaml.safe_load((ROOT / base).read_text(encoding="utf-8")))
        for dotted, value in overrides.items():
            section, k = dotted.split(".")
            cfg[section][k] = value
        cfg["project_name"] = f"CLFER-LT-IJCS-ext-{ds}-l{tag}-{variant}"
        cfg["training"].pop("experiment_name", None)
        header = f"# Generated by scripts/make_ext_configs.py from {base}; overrides: {overrides}\n"
        (ROOT / config_path(ds, tag, variant)).write_text(
            header + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8"
        )
    print(f"wrote {len(VARIANTS)} configs to {OUT}")


if __name__ == "__main__":
    main()
